"""Write docs/EVALUATION_RESULTS.md from the committed results/ files (H9).

Every number comes from results/*.json or results/tables.md, so the doc cannot drift
from the frozen run.  Run:  uv run python scripts/write_eval_doc.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
BASE = "TF-IDF delta"


def load(name: str) -> dict:
    return json.loads((RES / name).read_text(encoding="utf-8"))


def ci(cell: dict) -> str:
    lo, hi = cell["ci95"]
    return f"{cell['value']:.3f} [{lo:.3f}, {hi:.3f}]"


def side(cell: dict) -> str:
    lo, hi = cell["ci95"]
    if lo > 0:
        return "higher, and the 95% CI excludes zero"
    if hi < 0:
        return "lower, and the 95% CI excludes zero"
    return "not distinguishable (the 95% CI includes zero)"


def main() -> int:
    m, run = load("metrics.json"), load("RUN_INFO.json")
    rev = load("manual_review_summary.json")
    tables = (RES / "tables.md").read_text(encoding="utf-8").strip()
    sig = m["signals"]
    comb = next(k for k in sig if k.startswith("Combined"))
    snap, ft, pre = sig["TF-IDF snapshot"], sig["MiniLM fine-tuned delta"], sig["MiniLM delta"]
    base, cmb = sig[BASE], sig[comb]
    r1, r2 = m["rules"]["r1"], m["rules"]["r2"]
    d = m["decision_rule"]
    ft_gain = ft["pooled_auc"]["value"] - pre["pooled_auc"]["value"]
    o, by = rev["overall"], rev["by_doc_version"]
    rq1 = "Yes." if snap["pooled_auc_minus_baseline"]["ci95"][1] < 0 else "Not clearly."
    rq2 = "Yes." if ft["pooled_auc_minus_baseline"]["ci95"][0] > 0 else "Not on their own."

    doc = f"""# Spequlator — Evaluation results

- **Run:** `results/RUN_INFO.json`, run at {run["run_at"]} on commit `{(run["git_commit"] or "?")[:12]}`; git tag `frozen-eval`.
- **Frozen at:** {run["frozen"]["frozen_at"]} (`results/frozen/FROZEN.json`; artifact hashes re-verified before the run).
- **Split:** CoDocBench test, {m["n_records"]} records from {m["n_projects"]} projects, opened once (D-010, D-021).
- **Task:** the stale-vs-updated proxy (D-015). The old docstring against the commit's code change is the "stale" pair; the new docstring is the "updated" pair. These are **proxy labels**, not judgements of real drift.
- **Statistics:** 95% project-cluster bootstrap CIs, {run["n_boot"]} resamples, seed {run["seeds"]["bootstrap"]} (owner/project keys, D-026). Pairwise accuracy counts ties as 0.5.
- This file is generated by `scripts/write_eval_doc.py` from `results/`. Don't edit the numbers by hand.

## Tables (copied from `results/tables.md`)

{tables}

Figure: `results/figures/auc_ci.png` (pooled AUC with 95% CIs).

## Answers

- **RQ1. Does comparing against the code change beat a snapshot comparison?** {rq1} TF-IDF delta pooled AUC is {ci(base["pooled_auc"])}, against {ci(snap["pooled_auc"])} for the TF-IDF snapshot. Snapshot minus delta: {ci(snap["pooled_auc_minus_baseline"])}, which is {side(snap["pooled_auc_minus_baseline"])}.
- **RQ2. Do deep-learning signals beat TF-IDF?** {rq2}
  - Fine-tuned MiniLM delta AUC minus TF-IDF delta: {ci(ft["pooled_auc_minus_baseline"])}, which is {side(ft["pooled_auc_minus_baseline"])}.
  - Fine-tuning (D-020) moved MiniLM's pooled AUC by {ft_gain:+.3f} (point estimate) over the pretrained model.
  - The combined score (TF-IDF + fine-tuned MiniLM, D-028) reaches pairwise accuracy {ci(cmb["pairwise_accuracy"])} against {ci(base["pairwise_accuracy"])} for TF-IDF delta. Paired difference: {ci(cmb["pairwise_accuracy_minus_baseline"])}, which is {side(cmb["pairwise_accuracy_minus_baseline"])}. Its pooled AUC difference is {ci(cmb["pooled_auc_minus_baseline"])}.
- **RQ3. Do the rules add precise evidence?** R1 is a strong signal; R2 is a weak one, which is why it only decides inside the dead-band (D-025):
  - R1 (parameter mismatch) fires on {r1["stale_rate"]:.1%} of stale and {r1["updated_rate"]:.1%} of updated pairs (lift {r1["lift"]:.1f}x).
  - R2 (removed identifier still mentioned) fires on {r2["stale_rate"]:.1%} of stale and {r2["updated_rate"]:.1%} of updated pairs (lift {r2["lift"]:.1f}x).
  - The three-state decision rule decides {d["coverage"]:.1%} of reports, with balanced accuracy {d["balanced_accuracy_decided"]:.3f} on the decided ones; the rest are `inconclusive` by design.
- **RQ4. Are the reports faithful, specific and honest about uncertainty?** n = {rev["n_reports_scored"]} reports (30 test records x old and new docstring), stratified by the finding on the stale pair. **Scored by an LLM (Claude) with a second re-check pass; not human-verified (D-029).** Means on a 0–2 scale:
  - Evidence fidelity {o["evidence_fidelity"]:.2f}, specificity {o["specificity"]:.2f}, uncertainty calibration {o["uncertainty_calibration"]:.2f}.
  - Calibration on old docstrings {by["old"]["uncertainty_calibration"]:.2f} vs new {by["new"]["uncertainty_calibration"]:.2f}.
  - Old docstrings judged to need an update: {rev["needs_update_yes_rate_old"]:.1%}; new docstrings: {rev["needs_update_yes_rate_new"]:.1%}.
  - No inter-annotator agreement (κ) is reported: there was a single scorer.

## What the manual review found

1. **Evidence is accurate; generic terms are the weak spot.** Quoted lines and identifiers were almost always really in the inputs. The "terms shared with the current code" list often contains filler words (`the`, `and`, `to`, `self`), which lowers specificity.
2. **Rule evidence is the most useful part of a report.** When R1 or R2 drove a finding, it named the exact parameter or identifier (e.g. `output_folder` in record 9).
3. **Main blind spot: a new parameter that the docstring never mentions.** R1 only checks one direction: documented parameters missing from the code. Six old docstrings that lacked a newly added parameter (records 14, 16, 20, 24, 27, 30) were called `no_obvious_drift` or `inconclusive`. A reverse check ("R1b") is the obvious next rule. It is future work because the evaluation is frozen.
4. **Disagreeing signals were sometimes averaged into a confident answer.** In records 15, 16 and 20, TF-IDF and the encoder pointed in opposite directions, but the combined score still cleared the dead-band and said `no_obvious_drift`.
5. **Signals-only flags with small margins are often false positives.** Most `potential_drift` reports on updated docstrings had no rule evidence and very small signal values.

## Worked examples (test split)

1. **Success: `mvt-project/mvt :: DownloadAPKs.__init__` (`d8d5e14a548b`).** The parameter `output_folder` became `results_path`. The old docstring gets `potential_drift` with R1 evidence naming `output_folder`. The new docstring gets `no_obvious_drift`.
2. **Inconclusive: `pandas-dev/pandas :: DatetimeIndex.to_series` (`7ebf17aa6bf3`).** `index` and `name` parameters were added. The signals disagree on the old docstring, so the report says `inconclusive` and asks for manual review. That is honest, but a reverse R1 check would have caught it.
3. **Failure: `matplotlib/matplotlib :: Axes.axline` (`daf5fa9f64fd`).** The code removed the "linear axes only" restriction, but the old docstring still says it doesn't work on non-linear axes. R2 found `linear` in the removed lines, but the similarity signals said the docstring fits the new code, so the report says `no_obvious_drift`.

## Deviations from the pre-registered plan

- **D-025:** R2 counts as decisive only when the combined score is inside the dead-band.
- **D-026:** bootstrap clusters and the fine-tune dev split use owner/project keys.
- **D-027:** UniXcoder was dropped from the frozen run (too slow on the build machine); MiniLM is the pretrained encoder.
- **D-028:** the decision rule uses one combined, scaled score with a single dead-band, calibrated on train. The earlier AND rule left too many reports undecided.
- **D-029:** the RQ4 review was scored by an LLM with a second re-check pass instead of a human annotator.

## Threats to validity

- **Proxy labels.** CoDocBench only contains commits where code and docstring changed together, so "stale" means "the docstring the authors then replaced". It is not the same as real drift in the wild.
- **LLM-scored review.** The RQ4 scorer is an AI assistant that also helped build the tool, which may bias it. n is small (30 records) and there is one scorer.
- **Truncation.** Long inputs exceed the encoder's 128/256-token limit; see `encoder_truncation_rate` in `results/metrics.json`.
- **Project concentration.** A few large projects dominate CoDocBench; project-cluster CIs account for this, but per-project behaviour varies (`project_macro_pairwise_accuracy` in `metrics.json`).
"""
    out = ROOT / "docs" / "EVALUATION_RESULTS.md"
    out.write_text(doc, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
